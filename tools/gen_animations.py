# Turns art/mopmania_attack_animations.txt and art/mopmania_title_and_credits.txt
# into game/AnimationData.cpp (raw string literals, every line within 80 columns).
# Usage: python3 tools/gen_animations.py art/mopmania_attack_animations.txt \
#            art/mopmania_title_and_credits.txt game/AnimationData.cpp
import re, sys

HEADER = re.compile(r'^--- (.+?) - frame (\d+)/(\d+)(?: - hold (\d+) ms)? ---\s*$')

def parse(path):
    """Returns {sequence name: [(frame number, hold ms or None, [lines])]}"""
    seqs = {}
    cur = None
    for raw in open(path, encoding='utf-8').read().split('\n'):
        m = HEADER.match(raw)
        if m:
            cur = (m.group(1), int(m.group(2)), int(m.group(3)),
                   int(m.group(4)) if m.group(4) else None, [])
            seqs.setdefault(cur[0], []).append(cur)
        elif cur is not None:
            cur[4].append(raw.rstrip())
    out = {}
    for name, frames in seqs.items():
        total = frames[0][2]
        assert len(frames) == total, (name, len(frames), total)
        lst = []
        for (_, n, _, hold, lines) in frames:
            while lines and lines[-1] == '':      # blank line(s) before the next header
                lines.pop()
            for l in lines:
                assert len(l) <= 80, (name, n, len(l))
                assert ')ART"' not in l
            lst.append((n, hold, lines))
        out[name] = lst
    return out

attacks = parse(sys.argv[1])
screens = parse(sys.argv[2])

def ident(name):
    return re.sub(r'[^A-Z0-9]+', '_', name.upper()).strip('_')

code = ['// Ultra Deluxe: animation frames, generated by tools/gen_animations.py from',
        '// art/mopmania_attack_animations.txt and art/mopmania_title_and_credits.txt.',
        '// Raw string literals keep the backslashes as drawn. Do not edit by hand.',
        '#include "Animations.h"',
        '']
summary = []
for name, frames in list(attacks.items()) + list(screens.items()):
    var = 'UD_ANIM_' + ident(name.replace('Swifter ', '').replace('Ending + credits', 'Credits').replace('Title intro', 'Title'))
    code.append(f'// {name}: {len(frames)} frames')
    code.append(f'const UDFrame {var}[] = {{')
    for n, hold, lines in frames:
        code.append(f'{{ {hold or 0}, R"ART(')
        code.extend(lines)
        code.append(')ART" },')
    code.append('};')
    code.append(f'const int {var}_COUNT = {len(frames)};')
    code.append('')
    tallest = max(len(l) for _, _, l in frames)
    widest = max((len(x) for _, _, l in frames for x in l), default=0)
    summary.append(f'{var}: {len(frames)} frames, up to {widest} cols x {tallest} rows')
src = '\n'.join(code)
for i, l in enumerate(src.split('\n'), 1):
    assert len(l) <= 80, (i, len(l), l)
open(sys.argv[3], 'w', encoding='utf-8').write(src)
print('\n'.join(summary))
